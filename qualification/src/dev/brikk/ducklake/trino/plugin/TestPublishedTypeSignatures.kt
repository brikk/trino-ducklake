package dev.brikk.ducklake.trino.plugin

import io.trino.spi.TrinoException
import io.trino.spi.type.ArrayType
import io.trino.spi.type.DecimalType
import io.trino.spi.type.IntegerType.INTEGER
import io.trino.spi.type.MapType
import io.trino.spi.type.RowType
import io.trino.spi.type.VarbinaryType.VARBINARY
import io.trino.sql.SqlFormatter
import io.trino.sql.analyzer.TypeDescriptorTranslator
import io.trino.type.InternalTypeManager.TESTING_TYPE_MANAGER
import org.assertj.core.api.Assertions.assertThat
import org.assertj.core.api.Assertions.assertThatThrownBy
import org.junit.jupiter.api.Test

/** N03: independent names/types, not expectations generated by the new parser. */
class TestPublishedTypeSignatures {
    private val converter = DucklakeTypeConverter(TESTING_TYPE_MANAGER)

    @Test
    fun pagedMetadataProducerUsesThePublicQuotedNameEncoding() {
        val names = listOf("ordinary", "MiXeD", "a,b", "x:y", "q\"uote", "back\\slash", " spaced ", "雪")
        val signature = "struct<" + names.joinToString(",") { "${catalogTypeFieldName(it)}:int32" } + ">"
        assertThat((converter.toTrinoType(signature) as RowType).fields.map { it.name.orElseThrow() })
            .containsExactlyElementsOf(names)
        assertThat(catalogTypeFieldName("ordinary")).isEqualTo("ordinary")
    }

    @Test
    fun nativeTrinoTextTypeRoundTripCanonicalizesSimpleNames() {
        val original = RowType.from(listOf(RowType.field("MiXeD", INTEGER)))
        val text = SqlFormatter.formatSql(TypeDescriptorTranslator.toSqlType(original))
        val reconstructed = TESTING_TYPE_MANAGER.fromSqlType(text) as RowType
        assertThat(original.fields.single().name.orElseThrow()).isEqualTo("MiXeD")
        assertThat(reconstructed.fields.single().name.orElseThrow()).isEqualTo("mixed")
    }

    @Test
    fun quotedNamesKeepEveryCharacterAndOrder() {
        val type = converter.toTrinoType(
            """StRuCt<MiXeD:INT32,"a,b":varchar,"x:y":varchar,"a<b>":decimal(10,2),"q""uote":int32,"back\slash":int32," spaced ":varchar,"雪":varchar,"NULL":varchar>""") as RowType
        assertThat(type.fields.map { it.name.orElseThrow() }).containsExactly(
            "MiXeD", "a,b", "x:y", "a<b>", "q\"uote", "back\\slash", " spaced ", "雪", "NULL")
        assertThat(type.fields[0].type).isEqualTo(INTEGER)
        assertThat(type.fields[3].type).isEqualTo(DecimalType.createDecimalType(10, 2))
    }

    @Test
    fun nestedStructsInListsAndMapsRetainNamesAndDecimalCommas() {
        val type = converter.toTrinoType(
            """struct<xs:list<struct<"List,Value":int32>>,m:map<varchar,struct<"Map:Value":decimal(18,4),MiXeD:int32>>>""") as RowType
        val listRow = (type.fields[0].type as ArrayType).elementType as RowType
        assertThat(listRow.fields.single().name.orElseThrow()).isEqualTo("List,Value")
        val mapRow = (type.fields[1].type as MapType).valueType as RowType
        assertThat(mapRow.fields.map { it.name.orElseThrow() }).containsExactly("Map:Value", "MiXeD")
        assertThat(mapRow.fields[0].type).isEqualTo(DecimalType.createDecimalType(18, 4))
    }

    @Test
    fun malformedSyntaxAndArityDoNotFallBackToTheLegacyParser() {
        for (signature in listOf("list<int32", "map<int32>", "map<int32,varchar,int32>",
                "struct<a:int32,,b:int32>", "struct<\"unterminated:int32>",
                "list<int32> suffix", "struct<a:decimal(10,11)>")) {
            assertThatThrownBy { converter.toTrinoType(signature) }
                .`as`(signature).isInstanceOf(IllegalArgumentException::class.java)
        }
    }

    @Test
    fun parserDepthAndInputBudgetsFailRatherThanTruncate() {
        assertThatThrownBy { converter.toTrinoType("list<".repeat(65) + "int32" + ">".repeat(65)) }
            .isInstanceOf(IllegalArgumentException::class.java).hasMessageContaining("budget")
        assertThatThrownBy { converter.toTrinoType("struct<" + "a".repeat(16_385) + ":int32>") }
            .isInstanceOf(IllegalArgumentException::class.java).hasMessageContaining("characters")
    }

    @Test
    fun scalarMappingsAndUnsupportedLeavesKeepTheirExistingBoundaries() {
        assertThat(converter.toTrinoType("linestring z")).isEqualTo(VARBINARY)
        assertThat(converter.toTrinoType("struct<ordinary:int32>")).isEqualTo(RowType.from(listOf(RowType.field("ordinary", INTEGER))))
        assertThatThrownBy { converter.toTrinoType("struct<field:unsupported_type>") }
            .isInstanceOf(TrinoException::class.java).hasMessageContaining("Unsupported Ducklake type")
    }
}
